#!/usr/bin/env python3
"""
Indian Banking Peer Benchmarking — SBI vs HDFC / ICICI / Kotak / Axis — P16
Domain : SBI · Competitive Position
Business question: How does SBI compare with leading private banks on growth, profitability, size and market valuation?

Datasets : ['fin_peers_in_annual', 'px_peers_in']
SQL focus: peer ranking (RANK/DENSE_RANK), share-of-wallet, efficiency gap analysis

Method
  1. Load tidy datasets (prepared from real RBI HBS XLSX / market sources).
  2. KPI computation (latest / YoY / CAGR as specified).
  3. Series diagnostics: trend direction, volatility of growth, extremes,
     regime counts (±1σ bands), coverage & data-quality report.
  4. Persist machine-readable results to output/analysis.json and a narrative
     to output/summary.md.

Run:  python3 analysis.py
"""
import json
import pathlib
import sys

import numpy as np
import pandas as pd

BASE = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(BASE))

from common.analytics import compute_kpi, fmt_value, period_yoy, cagr  # noqa: E402

DATASETS = ['fin_peers_in_annual', 'px_peers_in']
KPIS = [{'label': 'SBI Assets Share (5-bank)', 'ds': 'fin_peers_in_annual', 'col': 'asset_share_pct_sbin', 'agg': 'last', 'unit': '%'}, {'label': 'SBI Revenue Rank', 'ds': 'fin_peers_in_annual', 'col': 'revenue_rank_sbin', 'agg': 'last', 'unit': 'rank'}, {'label': 'SBI ROE', 'ds': 'fin_peers_in_annual', 'col': 'roe_pct_sbin', 'agg': 'last', 'unit': '%'}, {'label': 'Peer Median ROE', 'ds': 'fin_peers_in_annual', 'col': 'peer_median_roe', 'agg': 'last', 'unit': '%'}]


def load():
    tables = {}
    for n in DATASETS:
        f = BASE / "data_lake" / "prepared" / f"{n}.csv"
        if f.exists():
            tables[n] = pd.read_csv(f)
    return tables


def diagnose(df: pd.DataFrame, col: str) -> dict:
    s = df[col].dropna()
    out = {"series": col, "n": int(len(s))}
    if len(s) < 2:
        return out
    per = df["period"] if "period" in df.columns else pd.Series(range(len(df)))
    out.update({
        "first": float(s.iloc[0]), "latest": float(s.iloc[-1]),
        "min": float(s.min()), "max": float(s.max()),
        "min_period": str(per[s.idxmin()]), "max_period": str(per[s.idxmax()]),
        "mean": float(s.mean()), "std": float(s.std()),
        "latest_vs_mean_sigma": float((s.iloc[-1] - s.mean()) / s.std()) if s.std() else None,
    })
    chg = s.pct_change().dropna()
    if len(chg):
        out["growth_mean_pct"] = float(chg.mean() * 100)
        out["growth_volatility_pp"] = float(chg.std() * 100)
        out["best_period"] = str(per.loc[chg.idxmax()])
        out["worst_period"] = str(per.loc[chg.idxmin()])
        out["rising_periods"] = int((chg > 0).sum())
        out["falling_periods"] = int((chg < 0).sum())
    mu, sd = s.mean(), s.std()
    if sd:
        out["regimes"] = {
            "high_gt_1sd": int((s > mu + sd).sum()),
            "above_mean": int(((s > mu) & (s <= mu + sd)).sum()),
            "below_mean": int(((s <= mu) & (s >= mu - sd)).sum()),
            "low_lt_minus1sd": int((s < mu - sd).sum()),
        }
    return out


def main() -> int:
    tables = load()
    kpis = [compute_kpi(k, tables) for k in KPIS]
    per_ds = {}
    for name, df in tables.items():
        num_cols = [c for c in df.select_dtypes("number").columns
            if c not in ("period", "date", "as_of_date")][:6]
        per_ds[name] = {
            "rows": int(len(df)),
            "period_range": [str(df["period"].iloc[0]), str(df["period"].iloc[-1])]
            if "period" in df.columns and len(df) else [],
            "diagnostics": [diagnose(df, c) for c in num_cols],
        }
    insights = {"project": "P16", "title": 'Indian Banking Peer Benchmarking — SBI vs HDFC / ICICI / Kotak / Axis', "kpis": kpis,
                 "datasets": per_ds}

    lines = [f"# {insights['title']} — Analysis Summary", "",
             "## KPI Summary", ""]
    for k in kpis:
        lines.append(f"- **{k['label']}**: {fmt_value(k['value'], k['unit'])} {k['unit']}")
    lines += ["", "## Series Diagnostics", ""]
    for name, meta in per_ds.items():
        lines.append(f"### {name} ({meta['rows']} rows)")
        for d in meta["diagnostics"]:
            if "latest" not in d:
                continue
            dir_ = "rising" if d.get("growth_mean_pct", 0) > 0 else "declining"
            lines.append(
                f"- `{d['series']}`: latest **{d['latest']:,.2f}** "
                f"(min {d['min']:,.2f} @ {d['min_period']}, "
                f"max {d['max']:,.2f} @ {d['max_period']}); "
                f"trend {dir_}, growth volatility {d.get('growth_volatility_pp', 0):.2f} pp, "
                f"up in {d.get('rising_periods', 0)} / down in {d.get('falling_periods', 0)} periods")
        lines.append("")
    lines += ["---",
              "_Generated by python/analysis.py — data: RBI Handbook of Statistics "
              "on Indian Economy & Yahoo Finance (real downloads)._"]

    out = pathlib.Path(__file__).parent / "output"
    out.mkdir(exist_ok=True)
    (out / "analysis.json").write_text(json.dumps(insights, indent=2, default=str))
    (out / "summary.md").write_text("\n".join(lines))
    print(f"[P16] KPIs={len(kpis)} datasets={len(per_ds)} -> output/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
